            <ul>
                <li><strong>Добавление клиента</strong> – кнопка «+ Добавить клиента» открывает форму, где заполняются все данные, включая мультиконтакты (несколько контактных лиц). Можно прикрепить файл КП.</li>
                <li><strong>Редактирование</strong> – кнопка «✏️ Ред.» открывает форму с уже заполненными данными.</li>
                <li><strong>Просмотр карточки</strong> – клик по названию клиента открывает карточку со всей информацией: реквизиты, все контакты, список договоров и сумма отгрузок.</li>
                <li><strong>Поиск</strong> – строка «Быстрый поиск компании» позволяет искать по любому слову в данных клиента.</li>
                <li><strong>Фильтры</strong> – по статусу, источнику, виду продукции, дате следующего контакта.</li>
                <li><strong>Установка галочки «Контракт»</strong> – при включении система создаёт черновик договора и перенаправляет в раздел контрактов для заполнения номера и продукции.</li>
                <li><strong>Снятие галочки</strong> – доступно только если нет активных договоров (не черновиков). В противном случае система предупредит.</li>
