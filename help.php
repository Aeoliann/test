            <!-- 11. ЧАСТО ЗАДАВАЕМЫЕ ВОПРОСЫ -->
            <h2 id="faq">11. Часто задаваемые вопросы</h2>
            <h3>❓ Как изменить статус клиента?</h3>
            <p>Откройте редактирование клиента (кнопка «✏️ Ред.») и выберите нужный статус в выпадающем списке.</p>
            <h3>❓ Почему после установки галочки «Контракт» я не вижу клиента в разделе контрактов?</h3>
            <p>Система создаёт черновик договора с номером «Б/Н». Клиент отображается в разделе контрактов, но может быть скрыт, если вы используете поиск или фильтры. Проверьте, что вы не применяете фильтр по номеру договора.</p>
            <h3>❓ Можно ли удалить ТТН?</h3>
            <p>На данный момент удаление ТТН доступно только через базу данных. В планах – добавить эту функцию в интерфейс.</p>
            <h3>❓ Как прикрепить скан к ТТН?</h3>
