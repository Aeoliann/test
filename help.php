            <h3>4.1. Таблица договоров</h3>
            <ul>
                <li><strong>Клиент / Договор</strong> – название клиента и номер договора.</li>
                <li><strong>№ Договора</strong> – редактируемое поле (клик по номеру позволяет изменить его).</li>
                <li><strong>Дата дог.</strong> – календарь для изменения даты договора.</li>
                <li><strong>Продукция</strong> – вид продукции по договору.</li>
                <li><strong>Отгрузки</strong> – кнопка «ТТН» открывает модальное окно для управления накладными.</li>
                <li><strong>Посл. отгрузка</strong> – дата последней ТТН.</li>
                <li><strong>Сумма отгрузок</strong> – общая сумма всех ТТН по договору (с разбивкой по валютам).</li>
                <li><strong>Скан</strong> – загрузка/просмотр скана договора (PDF, JPG, PNG).</li>
