                <li><strong>Удаление ТТН</strong> – пока не реализовано в интерфейсе, но администратор может удалить через БД при необходимости.</li>
            </ul>
            <div class="success">
                <strong>✅ Важно:</strong> Сумма отгрузок в таблице договоров пересчитывается автоматически при добавлении/изменении ТТН.
