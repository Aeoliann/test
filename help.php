                <li><strong>УНП</strong> – уникальный номер налогоплательщика.</li>
                <li><strong>Контактное лицо</strong> – ФИО, телефон, email (всплывающая подсказка).</li>
                <li><strong>Статус</strong> – текущее состояние (Новый, Текущий, Отказ, Потенциальный).</li>
                <li><strong>Источник</strong> – канал привлечения (запрос, холодный поиск, закупки, связка).</li>
                <li><strong>След. контакт</strong> – запланированная дата следующего взаимодействия.</li>
                <li><strong>Вид продукции</strong> – ассортимент, интересующий клиента.</li>
